const originalTexts = new WeakMap<Node, { source: string; rendered: string }>();
const originalAttributes = new WeakMap<Element, Map<string, { source: string; rendered: string }>>();

export function translateText(text: string, language: Language): string {
  const trimmed = text.trim();
  if (!trimmed) return text;
  const leading = text.slice(0, text.indexOf(trimmed));
  const trailing = text.slice(text.indexOf(trimmed) + trimmed.length);
  if (language === "en") {
    const titleSuffix = " · GestionPro";
    if (trimmed.endsWith(titleSuffix)) {
      const title = trimmed.slice(0, -titleSuffix.length);
      return `${leading}${translateText(title, "en")}${titleSuffix}${trailing}`;
    }
    const disabledMember = trimmed.match(/^Désactiver (.+) \? Il n'aura plus accès à l'entreprise\.$/);
    if (disabledMember) return `${leading}Deactivate ${disabledMember[1]}? They will no longer have access to the business.${trailing}`;
    const unreadCount = trimmed.match(/^(\d+) non lues?$/);
    if (unreadCount) return `${leading}${unreadCount[1]} unread notifications${trailing}`;
    const ordersCount = trimmed.match(/^(\d+) commande\(s\)$/);
    if (ordersCount) return `${leading}${ordersCount[1]} order(s)${trailing}`;
    const resultsCount = trimmed.match(/^(\d+) résultats?$/);
    if (resultsCount) return `${leading}${resultsCount[1]} result${resultsCount[1] === "1" ? "" : "s"}${trailing}`;
  }
  let localized = language === "en" ? translations.get(trimmed) : trimmed;

  if (!localized) {
    const prefix = localizedPrefixes.find(([source]) => trimmed.startsWith(source));
    if (prefix) localized = prefix[1] + trimmed.slice(prefix[0].length);
  }

  return localized ? `${leading}${localized}${trailing}` : text;
}

function translateNode(node: Node, language: Language) {
  if (node.nodeType === Node.TEXT_NODE) {
    const currentText = node.textContent ?? "";
    const previous = originalTexts.get(node);
    const source = previous && currentText === previous.rendered ? previous.source : currentText;
    const nextText = language === "en" ? translateText(source, "en") : source;
    if (nextText !== currentText) node.textContent = nextText;
    originalTexts.set(node, { source, rendered: nextText });
    return;
  }

  if (!(node instanceof Element) || ["SCRIPT", "STYLE", "NOSCRIPT"].includes(node.tagName)) return;
  let attributes = originalAttributes.get(node);
  if (!attributes) {
    attributes = new Map();
    originalAttributes.set(node, attributes);
  }
  for (const attribute of ["placeholder", "title", "aria-label", "alt"]) {
    const value = node.getAttribute(attribute);
    if (value) {
      const previous = attributes.get(attribute);
      const source = previous && value === previous.rendered ? previous.source : value;
      const localized = language === "en" ? translateText(source, "en") : source;
      if (localized !== value) node.setAttribute(attribute, localized);
      attributes.set(attribute, { source, rendered: localized });
    }
  }
  node.childNodes.forEach((child) => translateNode(child, language));
}

type LanguageContextValue = { language: Language; setLanguage: (language: Language) => void };
const LanguageContext = createContext<LanguageContextValue | null>(null);

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [language, setLanguageState] = useState<Language>("fr");

  const setLanguage = (nextLanguage: Language) => {
    window.localStorage.setItem("xgestion-language", nextLanguage);
    setLanguageState(nextLanguage);
  };

  useEffect(() => {
    const saved = window.localStorage.getItem("xgestion-language");
    if (saved === "en" || saved === "fr") setLanguageState(saved);

    const syncLanguage = (event: StorageEvent) => {
      if (event.key === "xgestion-language" && (event.newValue === "en" || event.newValue === "fr")) {
        setLanguageState(event.newValue);
      }
    };
    window.addEventListener("storage", syncLanguage);
    return () => window.removeEventListener("storage", syncLanguage);
  }, []);

  useEffect(() => {
    document.documentElement.lang = language;
    translateNode(document.documentElement, language);

    const observer = new MutationObserver((mutations) => {
      for (const mutation of mutations) {
        if (mutation.type === "characterData") translateNode(mutation.target, language);
        for (const node of mutation.addedNodes) translateNode(node, language);
        if (mutation.type === "attributes") translateNode(mutation.target, language);
      }
    });
    observer.observe(document.documentElement, {
      subtree: true,
      childList: true,
      characterData: true,
      attributes: true,
      attributeFilter: ["placeholder", "title", "aria-label", "alt"],
    });

    return () => observer.disconnect();
  }, [language]);

  const value = useMemo(() => ({ language, setLanguage }), [language]);
  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>;
}

export function useLanguage() {
  const value = useContext(LanguageContext);
  if (!value) throw new Error("useLanguage must be used within LanguageProvider");
  return value;
}

export function LanguageToggle() {
  const { language, setLanguage } = useLanguage();
  return (
    <div role="group" aria-label="Language / Langue" className="flex items-center rounded-full border border-slate-200 bg-white p-1 shadow-sm">
      <button type="button" onClick={() => setLanguage("fr")} aria-pressed={language === "fr"} className={`rounded-full px-3 py-1.5 text-xs font-semibold transition ${language === "fr" ? "bg-navy-900 text-white" : "text-slate-500 hover:text-slate-900"}`}>FR</button>
      <button type="button" onClick={() => setLanguage("en")} aria-pressed={language === "en"} className={`rounded-full px-3 py-1.5 text-xs font-semibold transition ${language === "en" ? "bg-navy-900 text-white" : "text-slate-500 hover:text-slate-900"}`}>EN</button>
    </div>
  );
}
